"""GROMACS production-grade MD protocol.

This module owns the protocol definition — the sequence of stages,
the deterministic ``.mdp`` content for each stage, and the
command-line arguments for every ``gmx`` invocation. It does **not**
execute subprocesses; the runner in :mod:`biolab_runners.gromacs.runner`
consumes the plan and orchestrates execution.

The protocol is the canonical "oral_amp" pipeline recipe:

1. **Topology** — ``gmx pdb2gmx -f input.pdb -o processed.gro``
2. **Box** — ``gmx editconf -f processed.gro -o boxed.gro -bt cubic -d <buffer>``
3. **Solvation** — ``gmx solvate -cp boxed.gro -cs spc216.gro -o solvated.gro -p topol.top``
4. **Ions** — ``gmx grompp -f ions.mdp -c solvated.gro -p topol.top -o ions.tpr`` then
   ``gmx genion -s ions.tpr -o ions.gro -p topol.top -pname NA -nname CL -neutral -conc 0.15``
   with the ``SOL`` group selection sent via subprocess stdin (no shell)
5. **Minimization** — ``gmx grompp -f min.mdp -c ions.gro -p topol.top``
   then ``gmx mdrun -deffnm min [-cpi min.cpt] [-append]``
   (steepest descent, max 50 000 iterations)
6. **NVT equilibration** — 100 ps with ``-DPOSRES`` flag set so position restraints are applied
   (the ``[ position_restraints ]`` topology directive is NOT re-emitted in the .mdp because
   it must live in the topology file to take effect — see GROMACS manual §5.7.1)
7. **NPT equilibration** — 100 ps with ``-DPOSRES`` flag set
8. **Production** — default 200 ns, NPT, no restraints; ``-cpi`` is added **only** when
   ``prod.cpt`` exists on disk (the "no duplicate start path" rule)

The ``.mdp`` content is generated by the four ``generate_*_mdp``
functions. The content is **byte-deterministic** for a given input —
two calls with the same parameters produce byte-identical strings.
This is a test invariant (see ``tests/test_gromacs_protocol.py``).

All MD .mdp files use ``constraints = h-bonds`` and
``constraint-algorithm = lincs`` at ``dt = 0.002`` — the canonical
GROMACS recipe for 2 fs hydrogen-bond-constrained MD. Production uses
``v-rescale`` / ``nose-hoover`` + ``parrinello-rahman`` (NPT); NVT/NPT
equilibration uses ``v-rescale`` (Berendsen's stochastic noise is
unwanted for the equilibration phase, but v-rescale produces a correct
canonical ensemble without the ergodicity issues of weak-coupling
thermostats).

Per-replica deterministic seeds (``gen-seed = replica_index + 1``)
ensure each replica produces a reproducible trajectory while keeping
replicas diverse. Set ``gen-seed = -1`` for non-deterministic runs
(the ``runner`` does NOT pass ``-1``; the .mdp value is used as-is).
"""

