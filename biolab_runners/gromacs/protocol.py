class StageKind(StrEnum):
    """Categorical classification of a protocol stage.

    Used by the runner to decide which subprocess flow to invoke
    (``gmx pdb2gmx`` is one-shot; ``gmx mdrun`` is checkpoint-
    resumable). Distinct from :class:`ProtocolStage`, which carries
    the per-stage ``-deffnm`` and mdp filename.
    """

    TOPOLOGY = "topology"
    BOX = "box"
    SOLVATE = "solvate"
    IONS = "ions"
    MINIMIZE = "minimize"
    EQUIL_NVT = "equil_nvt"
    EQUIL_NPT = "equil_npt"
    PRODUCTION = "production"


# Genion needs a group selection ("SOL\n" by default — solvent). Sent
# via subprocess stdin so we never need a shell wrapper. This is the
# canonical "noninteractive genion" pattern from the GROMACS manual.
GENION_INPUT = "SOL\n"


# Default position-restraint energy constant for NVT/NPT equilibration.
# 1000 kJ/mol/nm^2 is the conventional value (strong enough to keep
# protein heavy atoms near the minimised coordinates while the solvent
# relaxes around them). The ``[ position_restraints ]`` block lives in
# the topology file (not the .mdp) — the .mdp only sets ``define =
# -DPOSRES`` to enable it.
_DEFAULT_POSRES_K = 1000.0

# Canonical 2 fs timestep (the only value used across all MD .mdp
# files in this protocol). Required for LINCS h-bond constraints.
_TIMESTEP_FS = 2


@dataclass(frozen=True)
class ProtocolStage:
    """One stage in the GROMACS protocol.

    A stage owns its ``-deffnm`` prefix, its ``.mdp`` filename, and
    its :class:`StageKind`. The runner walks a list of these and
    executes each one in order.
    """

    kind: StageKind
    prefix: str
    mdp_filename: str


@dataclass(frozen=True)
class StageSpec:
    """A resolved stage: kind + the on-disk outputs the runner expects.

    The ``outputs`` tuple is the set of filenames that must exist
    for the stage to be considered complete. The runner uses this
    to decide skip-vs-resume before invoking any subprocess.
    """

    stage: ProtocolStage
    outputs: tuple[str, ...]


def _ps_to_steps(duration_ps: int) -> int:
    """Convert ps to integration steps at the canonical 2 fs timestep."""
    return int(duration_ps * 1000 / _TIMESTEP_FS)


def _ns_to_steps(duration_ns: float) -> int:
    """Convert ns to integration steps at the canonical 2 fs timestep."""
    return round(duration_ns * 1_000_000 / _TIMESTEP_FS)


def generate_minimization_mdp(
    max_iterations: int = 50_000,
    *,
    replica_index: int = 0,
) -> str:
    """Generate the deterministic ``.mdp`` content for steepest-descent minimisation.

    The default ``max_iterations=50_000`` matches the S4 spec
    (the historical OpenMM path uses 1 000; the GROMACS protocol
    uses 50 000 to converge solvated systems with 0.15 M ions
    where charge-neutralisation can require thousands of steps).

    The content is byte-deterministic — identical inputs produce
    byte-identical output. Tests assert this with ``==``.

    Args:
        max_iterations: Steepest-descent cap. Must be positive.
        replica_index: 0-indexed replica number. ``gen-seed`` is set
            to ``replica_index + 1`` so each replica produces a
            deterministic-but-different velocity-rescale seed (the
            seed only matters for ``md`` integrator; steepest descent
            ignores it but we keep the field set for consistency).

    Returns:
        The ``.mdp`` file content as a single string.

    Raises:
        ValueError: If ``max_iterations`` is not positive.
    """
    if max_iterations < 1:
        raise ValueError(f"max_iterations must be positive; got {max_iterations}")
    if replica_index < 0:
        raise ValueError(f"replica_index must be non-negative; got {replica_index}")
    return (
        "; Steepest-descent energy minimisation\n"
        "; Generated by biolab-runners (deterministic content)\n"
        "integrator       = steep\n"
        "emtol            = 1000.0\n"
        "emstep           = 0.01\n"
        f"nsteps           = {max_iterations}\n"
        "nstenergy        = 500\n"
        "nstlog           = 500\n"
        "cutoff-scheme    = Verlet\n"
        "nstlist          = 20\n"
        "ns-type          = grid\n"
        "coulombtype      = PME\n"
        "rcoulomb         = 1.0\n"
        "rvdw             = 1.0\n"
        "pme-order        = 4\n"
        "fourierspacing   = 0.12\n"
        "tcoupl           = no\n"
        "pcoupl           = no\n"
        f"gen-seed         = {replica_index + 1}\n"
    )


def generate_equil_nvt_mdp(
    duration_ps: int = 100,
    temperature_k: float = 310.0,
    *,
    replica_index: int = 0,
) -> str:
    """Generate the deterministic ``.mdp`` content for NVT equilibration.

    NVT is the FIRST MD stage after minimisation. As such it is the
    stage that bootstraps velocities from a Maxwell-Boltzmann
    distribution at the target temperature (``gen-vel = yes``,
    ``gen-temp = {temperature_k}``). NPT and production inherit
    velocities from the previous stage's .gro/.cpt and so do NOT
    set ``gen-vel`` (a regression that sets ``gen-vel = yes`` in
    NPT or production would silently REPLACE the equilibrated
    velocities with fresh Maxwell-Boltzmann draws on every fresh
    start, defeating equilibration).

    Resume behaviour: ``gmx grompp -t <checkpoint>`` reads velocities
    from the .cpt and IGNORES ``gen-vel`` (GROMACS semantic — see
    the manual §Table 5.4: "gen-vel: ignored if -t is provided").
    So the same .mdp is correct for both fresh start and resume;
    the runner adds ``-t <cpt>`` to the grompp invocation only
    when a checkpoint exists on disk.

    NVT uses a v-rescale thermostat with the ``-DPOSRES`` flag
    set so position restraints (declared in the topology, not
    the .mdp) are applied while the solvent thermalises around
    the protein.

    The ``[ position_restraints ]`` topology directive is **not**
    emitted here — that section lives in the topology file and
    is activated by the ``-DPOSRES`` preprocessor define.

    Args:
        duration_ps: NVT equilibration length in ps. Must be positive.
        temperature_k: Target temperature in Kelvin. Must be positive.
        replica_index: 0-indexed replica number (sets ``gen-seed``).

    Returns:
        The ``.mdp`` file content as a single string.

    Raises:
        ValueError: If ``duration_ps`` or ``temperature_k`` are not positive.
    """
    if duration_ps < 1:
        raise ValueError(f"duration_ps must be positive; got {duration_ps}")
    if temperature_k <= 0:
        raise ValueError(f"temperature_k must be positive; got {temperature_k}")
    if replica_index < 0:
        raise ValueError(f"replica_index must be non-negative; got {replica_index}")
    nsteps = _ps_to_steps(duration_ps)
    return (
        "; NVT equilibration (v-rescale thermostat, position restraints in topology)\n"
        "; Generated by biolab-runners (deterministic content)\n"
        "define           = -DPOSRES\n"
        "integrator       = md\n"
        f"dt               = {_TIMESTEP_FS / 1000}\n"
        f"nsteps           = {nsteps}\n"
        "nstenergy        = 500\n"
        "nstlog           = 500\n"
        "nstxtcout        = 5000\n"
        "cutoff-scheme    = Verlet\n"
        "nstlist          = 20\n"
        "ns-type          = grid\n"
        "coulombtype      = PME\n"
        "rcoulomb         = 1.0\n"
        "rvdw             = 1.0\n"
        "pme-order        = 4\n"
        "fourierspacing   = 0.12\n"
        "tcoupl           = v-rescale\n"
        "tc-grps          = System\n"
        f"ref-t            = {temperature_k}\n"
        "tau-t            = 0.1\n"
        "pcoupl           = no\n"
        "constraints      = h-bonds\n"
        "constraint-algorithm = lincs\n"
        "lincs-iter       = 1\n"
        "lincs-order      = 4\n"
        "gen-vel          = yes\n"
        f"gen-temp         = {temperature_k}\n"
        f"gen-seed         = {replica_index + 1}\n"
    )


def generate_equil_npt_mdp(
    duration_ps: int = 100,
    temperature_k: float = 310.0,
    pressure_bar: float = 1.0,
    *,
    replica_index: int = 0,
) -> str:
    """Generate the deterministic ``.mdp`` content for NPT equilibration.

    NPT adds a v-rescale thermostat + Berendsen barostat on top of
    NVT. Position restraints remain activated via ``-DPOSRES`` (the
    restraints themselves live in the topology, not here).

    NPT inherits velocities from the previous stage's .gro/.cpt;
    it does NOT set ``gen-vel`` (only the first MD stage, NVT,
    bootstraps velocities from a Maxwell-Boltzmann distribution).
    On resume from a .cpt, ``gmx grompp -t <cpt>`` ignores any
    ``gen-vel`` setting (GROMACS manual §Table 5.4), so the same
    .mdp is correct for both fresh start and resume.

    Args:
        duration_ps: NPT equilibration length in ps. Must be positive.
        temperature_k: Target temperature in Kelvin. Must be positive.
        pressure_bar: Target pressure in bar. Must be positive.
        replica_index: 0-indexed replica number (sets ``gen-seed``).

    Returns:
        The ``.mdp`` file content as a single string.

    Raises:
        ValueError: If any argument is not positive.
    """
    if duration_ps < 1:
        raise ValueError(f"duration_ps must be positive; got {duration_ps}")
    if temperature_k <= 0:
        raise ValueError(f"temperature_k must be positive; got {temperature_k}")
    if pressure_bar <= 0:
        raise ValueError(f"pressure_bar must be positive; got {pressure_bar}")
    if replica_index < 0:
        raise ValueError(f"replica_index must be non-negative; got {replica_index}")
    nsteps = _ps_to_steps(duration_ps)
    return (
        "; NPT equilibration (v-rescale + Berendsen barostat, position restraints in topology)\n"
        "; Generated by biolab-runners (deterministic content)\n"
        "define           = -DPOSRES\n"
        "integrator       = md\n"
        f"dt               = {_TIMESTEP_FS / 1000}\n"
        f"nsteps           = {nsteps}\n"
        "nstenergy        = 500\n"
        "nstlog           = 500\n"
        "nstxtcout        = 5000\n"
        "cutoff-scheme    = Verlet\n"
        "nstlist          = 20\n"
        "ns-type          = grid\n"
        "coulombtype      = PME\n"
        "rcoulomb         = 1.0\n"
        "rvdw             = 1.0\n"
        "pme-order        = 4\n"
        "fourierspacing   = 0.12\n"
        "tcoupl           = v-rescale\n"
        "tc-grps          = System\n"
        f"ref-t            = {temperature_k}\n"
        "tau-t            = 0.1\n"
        "pcoupl           = berendsen\n"
        "pcoupltype       = isotropic\n"
        f"ref-p            = {pressure_bar}\n"
        "tau-p            = 1.0\n"
        "compressibility  = 4.5e-5\n"
        "constraints      = h-bonds\n"
        "constraint-algorithm = lincs\n"
        "lincs-iter       = 1\n"
        "lincs-order      = 4\n"
        f"gen-seed         = {replica_index + 1}\n"
    )


def generate_production_mdp(
    duration_ns: float = 200.0,
    temperature_k: float = 310.0,
    pressure_bar: float = 1.0,
    *,
    replica_index: int = 0,
) -> str:
    """Generate the deterministic ``.mdp`` content for production MD.

    Production removes position restraints (no ``-DPOSRES`` define),
    switches to a Nose-Hoover thermostat + Parrinello-Rahman
    barostat for proper NPT sampling, and uses a 2 fs timestep
    with LINCS h-bond constraints.

    XTC (compressed trajectory), EDR (energy), and the human-readable
    log are written automatically by ``gmx mdrun`` based on the
    ``nst*`` intervals. The default 200 ns matches the S4 spec.

    Like NPT, production inherits velocities from the previous
    stage's .gro/.cpt and does NOT set ``gen-vel`` — only NVT (the
    first MD stage) bootstraps velocities from a Maxwell-Boltzmann
    distribution. On resume, ``grompp -t <cpt>`` ignores any
    ``gen-vel`` setting, so the same .mdp is correct for both
    fresh start and resume.

    Args:
        duration_ns: Production length in nanoseconds. Must be positive.
        temperature_k: Target temperature in Kelvin. Must be positive.
        pressure_bar: Target pressure in bar. Must be positive.
        replica_index: 0-indexed replica number (sets ``gen-seed``).

    Returns:
        The ``.mdp`` file content as a single string.

    Raises:
        ValueError: If any argument is not positive.
    """
    if duration_ns <= 0:
        raise ValueError(f"duration_ns must be positive; got {duration_ns}")
    if temperature_k <= 0:
        raise ValueError(f"temperature_k must be positive; got {temperature_k}")
    if pressure_bar <= 0:
        raise ValueError(f"pressure_bar must be positive; got {pressure_bar}")
    if replica_index < 0:
        raise ValueError(f"replica_index must be non-negative; got {replica_index}")
    nsteps = _ns_to_steps(duration_ns)
    return (
        "; Production MD (NPT, no restraints, Nose-Hoover + Parrinello-Rahman)\n"
        "; Generated by biolab-runners (deterministic content)\n"
        "integrator       = md\n"
        f"dt               = {_TIMESTEP_FS / 1000}\n"
        f"nsteps           = {nsteps}\n"
        "nstenergy        = 5000\n"
        "nstlog           = 5000\n"
        "nstxtcout        = 50000\n"
        "cutoff-scheme    = Verlet\n"
        "nstlist          = 20\n"
        "ns-type          = grid\n"
        "coulombtype      = PME\n"
        "rcoulomb         = 1.0\n"
        "rvdw             = 1.0\n"
        "pme-order        = 4\n"
        "fourierspacing   = 0.12\n"
        "tcoupl           = nose-hoover\n"
        "tc-grps          = System\n"
        f"ref-t            = {temperature_k}\n"
        "tau-t            = 0.5\n"
        "pcoupl           = parrinello-rahman\n"
        "pcoupltype       = isotropic\n"
        f"ref-p            = {pressure_bar}\n"
        "tau-p            = 5.0\n"
        "compressibility  = 4.5e-5\n"
        "constraints      = h-bonds\n"
        "constraint-algorithm = lincs\n"
        "lincs-iter       = 1\n"
        "lincs-order      = 4\n"
        f"gen-seed         = {replica_index + 1}\n"
    )


